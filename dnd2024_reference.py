def ability_modifier(score: int) -> int:
    """Модификатор характеристики: (значение − 10) // 2."""
    return (int(score) - 10) // 2


def format_modifier(value: int) -> str:
    """Форматирует модификатор со знаком: 2 -> '+2', -1 -> '-1'."""
    return f"{value:+d}"


def proficiency_bonus(level: int) -> int:
    """Бонус мастерства по уровню персонажа (1–20)."""
    level = max(1, min(int(level), MAX_LEVEL))
    return 2 + (level - 1) // 4


def xp_threshold(level: int) -> int:
    """Сколько всего XP нужно, чтобы достичь указанного уровня."""
    level = max(1, min(int(level), MAX_LEVEL))
    return XP_THRESHOLDS[level]


def next_xp_threshold(level: int) -> Optional[int]:
    """Порог XP для следующего уровня (None на 20-м уровне)."""
    if level >= MAX_LEVEL:
        return None
    return XP_THRESHOLDS[level + 1]


def level_for_xp(xp: int) -> int:
    """Определяет уровень по накопленному опыту."""
    xp = max(0, int(xp))
    level = 1
    for candidate in range(2, MAX_LEVEL + 1):
        if xp >= XP_THRESHOLDS[candidate]:
            level = candidate
        else:
            break
    return level


def normalize_ability_key(key: str) -> Optional[str]:
    """Приводит название характеристики (сил/СИЛ/strength) к коду ('str')."""
    return ABILITY_ALIASES.get(str(key).strip().lower())


def resolve_class_key(class_name: str) -> Optional[str]:
    """Пытается сопоставить произвольное название класса с известным ключом."""
    if not class_name:
        return None
    lowered = str(class_name).strip().lower()
    if lowered in CLASSES:
        return lowered
    for key, data in CLASSES.items():
        for alias in data.get("aliases", ()):
            if alias in lowered:
                return key
    return None


def resolve_species_key(species_name: str) -> Optional[str]:
    """Пытается сопоставить название вида/расы с известным ключом ('elf', 'orc', ...)."""
    if not species_name:
        return None
    lowered = str(species_name).strip().lower()
    if lowered in SPECIES:
        return lowered
    for key, data in SPECIES.items():
        if data["name"].lower() == lowered:
            return key
        for alias in data.get("aliases", ()):
            if alias in lowered:
                return key
    return None


def species_name(species_name_text: str) -> Optional[str]:
    """Каноническое русское название вида по произвольному тексту (или None)."""
    key = resolve_species_key(species_name_text)
    return SPECIES[key]["name"] if key is not None else None


def species_traits(species_name_text: str) -> tuple[str, ...]:
    """Кортеж расовых особенностей вида по произвольному названию.

    Возвращает пустой кортеж, если вид не распознан или у него нет описанных
    особенностей. Используется листом персонажа (раздел «Черты (расовые)»).
    """
    key = resolve_species_key(species_name_text)
    if key is None:
        return ()
    return tuple(SPECIES[key].get("traits", ()))


def class_name_from_text(class_name_text: str) -> Optional[str]:
    """Каноническое русское название класса по произвольному тексту (или None)."""
    key = resolve_class_key(class_name_text)
    return CLASSES[key]["name"] if key is not None else None


def ability_priority_for_class(class_name: str) -> tuple[str, ...]:
    """Порядок характеристик класса: основные, затем ТЕЛ, ЛОВ и все остальные.

    Используется при создании героя: старшие значения набора получают первые
    характеристики из этого порядка.
    """
    key = resolve_class_key(class_name)
    primary: tuple[str, ...] = CLASSES[key]["primary"] if key is not None else ("str",)

    order: list[str] = [code for code in primary if code in ABILITIES]
    for code in ABILITY_PRIORITY_AFTER_PRIMARY:
        if len(order) >= len(ABILITIES):
            break
        if code not in order:
            order.append(code)
    return tuple(order)


def standard_array_for_class(class_name: str) -> dict[str, int]:
    """Распределяет стандартный набор PHB 2024 по характеристикам класса.

    Высшие значения получают основные характеристики класса, затем ТЕЛ, ЛОВ и
    остальные (см. ability_priority_for_class).
    """
    return dict(zip(ability_priority_for_class(class_name), STANDARD_ARRAY))


def starter_equipment_for_class(class_name: str) -> tuple[str, ...]:
    """Стартовое снаряжение 1-го уровня по классу персонажа (PHB 2024)."""
    key = resolve_class_key(class_name)
    if key is None:
        return DEFAULT_STARTER_KIT
    return CLASS_STARTER_KITS.get(key, DEFAULT_STARTER_KIT)


def starting_gold_for_class(class_name: str) -> int:
    """Стартовое золото (gp), которое PHB 2024 выдаёт вместе со снаряжением класса."""
    key = resolve_class_key(class_name)
    if key is None:
        return 5
    return int(CLASS_STARTING_GP.get(key, 5))


def hit_die_sides(class_name: str) -> int:
    """Кость хитов класса (число граней). Для неизвестного класса — d8."""
    key = resolve_class_key(class_name)
    if key is None:
        return DEFAULT_HIT_DIE
    return int(CLASSES[key]["hit_die"])


def average_hit_points(sides: int, con_mod: int) -> int:
    """Прирост HP за уровень: среднее по кости хитов + модификатор ТЕЛ (минимум 1)."""
    return max(1, int(sides) // 2 + 1 + int(con_mod))


